#!/usr/bin/env python3
"""Generate src/nerd-icons.h from the icons used in src/ls-icons.c.

Icons are referenced in ls-icons.c as NF_<CLASS>_<NAME>, which maps to the
official Nerd Fonts glyph name "<class>-<name>" (lower case), e.g.
NF_SETI_PYTHON -> seti-python, NF_MD_LANGUAGE_RUST -> md-language_rust.

Usage:
  scripts/gen-nerd-icons.py GLYPHNAMES_JSON [FONT_FILE]

GLYPHNAMES_JSON is glyphnames.json from https://github.com/ryanoasis/nerd-fonts
If FONT_FILE is given (needs fontTools), every icon is also checked to exist
in that font, e.g. MapleMono-NF-CN-Regular.ttf.
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    with open(sys.argv[1], encoding="utf-8") as fp:
        glyphs = json.load(fp)
    version = glyphs.pop("METADATA", {}).get("version", "?")

    cmap = None
    if len(sys.argv) == 3:
        from fontTools.ttLib import TTFont
        cmap = TTFont(sys.argv[2], lazy=True).getBestCmap()

    with open(os.path.join(SRC, "ls-icons.c"), encoding="utf-8") as fp:
        used = sorted(set(re.findall(r"\bNF_[A-Z0-9_]+\b", fp.read())))

    errors = []
    lines = []
    for macro in used:
        cls, _, name = macro[3:].lower().partition("_")
        glyph = f"{cls}-{name}"
        if glyph not in glyphs:
            errors.append(f"{macro}: no Nerd Font glyph named '{glyph}'")
            continue
        code = int(glyphs[glyph]["code"], 16)
        if cmap is not None and code not in cmap:
            errors.append(f"{macro}: U+{code:X} ({glyph}) missing in font")
        esc = f"\\u{code:04x}" if code <= 0xFFFF else f"\\U{code:08x}"
        lines.append(f'# define {macro} "{esc}" /* {glyph} */')

    if errors:
        sys.exit("\n".join(errors))

    out = os.path.join(SRC, "nerd-icons.h")
    with open(out, "w", encoding="utf-8") as fp:
        fp.write("/* Generated by scripts/gen-nerd-icons.py from Nerd Fonts "
                 f"{version} glyphnames.json.\n   Do not edit by hand. */\n\n")
        fp.write("#ifndef NERD_ICONS_H\n# define NERD_ICONS_H\n\n")
        fp.write("\n".join(lines))
        fp.write("\n\n#endif /* NERD_ICONS_H */\n")
    print(f"wrote {out}: {len(lines)} icons")


if __name__ == "__main__":
    main()
